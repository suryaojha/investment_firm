<?php
require __DIR__ . '/inc/bootstrap.php';

$errors = []; $done = false;
if (INSTALLED) { http_response_code(403); exit('<!doctype html><body style="font-family:system-ui;padding:40px"><h2>Already installed</h2><p>Delete <code>config.local.php</code> only if you really want to reinstall (this does not delete data in MySQL).</p><p><a href="' . e(url('')) . '/">Go to site</a> · <a href="' . e(url('admin/')) . '">Admin</a></p></body>'); }

$checks = [
    'PHP 7.4 or newer' => PHP_VERSION_ID >= 70400,
    'PDO extension' => extension_loaded('pdo'),
    'pdo_sqlite or pdo_mysql' => extension_loaded('pdo_sqlite') || extension_loaded('pdo_mysql'),
    'OpenSSL (encryption)' => extension_loaded('openssl'),
    'Fileinfo (safe uploads)' => extension_loaded('fileinfo'),
    'mbstring' => extension_loaded('mbstring'),
    'storage/ is writable' => (is_dir(ROOT . '/storage') || @mkdir(ROOT . '/storage', 0755, true)) && is_writable(ROOT . '/storage'),
    'uploads/ is writable' => (is_dir(ROOT . '/uploads') || @mkdir(ROOT . '/uploads', 0755, true)) && is_writable(ROOT . '/uploads'),
    'Project folder is writable (to save config)' => is_writable(ROOT),
];
$ok = !in_array(false, $checks, true);

$v = ['driver' => 'sqlite', 'db_host' => 'localhost', 'db_port' => '3306', 'db_name' => '', 'db_user' => '', 'db_pass' => '', 'site' => 'Aurum Estates', 'aname' => '', 'aemail' => '', 'sample' => '1'];
if (is_post() && $ok) {
    csrf_verify();
    foreach ($v as $k => $_) if (isset($_POST[$k])) $v[$k] = trim((string)$_POST[$k]);
    $v['sample'] = isset($_POST['sample']) ? '1' : '0';
    $pass = (string)($_POST['apass'] ?? '');
    if ($v['site'] === '') $errors[] = 'Enter the site / company name.';
    if ($v['aname'] === '') $errors[] = 'Enter the admin name.';
    if (!filter_var($v['aemail'], FILTER_VALIDATE_EMAIL)) $errors[] = 'Enter a valid admin email.';
    if (strlen($pass) < 10) $errors[] = 'Admin password must be at least 10 characters.';
    if ($v['driver'] === 'mysql' && ($v['db_name'] === '' || $v['db_user'] === '')) $errors[] = 'MySQL database name and user are required.';

    if (!$errors) {
        $cfg = ['db_driver' => $v['driver'], 'db_host' => $v['db_host'], 'db_port' => (int)$v['db_port'], 'db_name' => $v['db_name'], 'db_user' => $v['db_user'], 'db_pass' => $v['db_pass'],
                'app_key' => bin2hex(random_bytes(32)), 'debug' => false];
        try {
            $GLOBALS['CFG'] = $cfg;
            require ROOT . '/inc/db.php';
            require ROOT . '/inc/settings_schema.php';
            $pdo = db();
            create_schema($pdo, $v['driver'] === 'mysql');
            $already = (int)$pdo->query('SELECT COUNT(*) FROM users')->fetchColumn();
            if ($already === 0) {
                $pdo->prepare('INSERT INTO users (name,email,phone,password,role,status,kyc_status,created_at) VALUES (?,?,?,?,?,?,?,?)')
                    ->execute([$v['aname'], strtolower($v['aemail']), '', password_hash($pass, PASSWORD_DEFAULT), 'admin', 'active', 'approved', now()]);
                if ($v['sample'] === '1') seed_content($pdo);
                foreach (['site_name' => $v['site'], 'contact_email' => strtolower($v['aemail']), 'notify_email' => strtolower($v['aemail'])] as $k => $val) set_setting($k, $val);
            }
            foreach (['storage/logs', 'storage/kyc', 'storage/proofs', 'storage/db', 'uploads/images', 'uploads/videos', 'uploads/docs'] as $d)
                if (!is_dir(ROOT . '/' . $d)) @mkdir(ROOT . '/' . $d, 0755, true);
            file_put_contents(ROOT . '/config.local.php', "<?php\n// Generated by install.php — keep this file private.\nreturn " . var_export($cfg, true) . ";\n");
            $done = true;
        } catch (Throwable $e) {
            $errors[] = 'Setup failed: ' . $e->getMessage();
        }
    }
}
?><!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Install</title>
<link rel="stylesheet" href="<?= e(asset('css/admin.css')) ?>"></head>
<body class="install-body">
<div class="install-card">
  <h1>🏗️ Installation</h1>
  <p class="muted">Set up the investment platform in one step.</p>
  <?php if ($done): ?>
    <div class="alert alert-ok"><strong>Installed successfully.</strong></div>
    <p>Your admin account is ready. Next: log in, then open <strong>Settings</strong> to add your logo, colours, bank/UPI details, payment gateway and email (SMTP).</p>
    <p><a class="btn btn-primary" href="<?= e(url('admin/login.php')) ?>">Go to admin login →</a> &nbsp; <a class="btn btn-ghost" href="<?= e(url('')) ?>">View website</a></p>
    <p class="muted small">For security, you may also delete <code>install.php</code> from the server.</p>
  <?php else: ?>
    <ul class="checks"><?php foreach ($checks as $k => $r): ?><li class="<?= $r ? 'ok' : 'bad' ?>"><?= $r ? '✔' : '✖' ?> <?= e($k) ?></li><?php endforeach; ?></ul>
    <?php if (!extension_loaded('curl')): ?><div class="alert alert-info">Note: PHP <b>cURL</b> is not enabled. You can install now; it is only needed for Razorpay online payments (enable <code>extension=curl</code> in php.ini later). Direct UPI/bank payments work without it.</div><?php endif; ?>
    <?php foreach ($errors as $er): ?><div class="alert alert-bad"><?= e($er) ?></div><?php endforeach; ?>
    <?php if ($ok): ?>
    <form method="post" autocomplete="off">
      <?= csrf_field() ?>
      <h3>Database</h3>
      <label class="radio"><input type="radio" name="driver" value="sqlite" <?= $v['driver'] === 'sqlite' ? 'checked' : '' ?> onclick="document.getElementById('my').hidden=true"> SQLite (zero setup — good for small/medium sites)</label>
      <label class="radio"><input type="radio" name="driver" value="mysql" <?= $v['driver'] === 'mysql' ? 'checked' : '' ?> onclick="document.getElementById('my').hidden=false"> MySQL / MariaDB (recommended for production)</label>
      <div id="my" <?= $v['driver'] === 'mysql' ? '' : 'hidden' ?> class="grid2">
        <label>Host<input name="db_host" value="<?= e($v['db_host']) ?>"></label>
        <label>Port<input name="db_port" value="<?= e($v['db_port']) ?>"></label>
        <label>Database name<input name="db_name" value="<?= e($v['db_name']) ?>"></label>
        <label>Database user<input name="db_user" value="<?= e($v['db_user']) ?>"></label>
        <label>Database password<input type="password" name="db_pass"></label>
      </div>
      <h3>Site & admin</h3>
      <label>Company / site name<input name="site" value="<?= e($v['site']) ?>" required></label>
      <div class="grid2">
        <label>Admin name<input name="aname" value="<?= e($v['aname']) ?>" required></label>
        <label>Admin email<input type="email" name="aemail" value="<?= e($v['aemail']) ?>" required></label>
      </div>
      <label>Admin password (min 10 characters)<input type="password" name="apass" minlength="10" required></label>
      <label class="radio"><input type="checkbox" name="sample" value="1" <?= $v['sample'] === '1' ? 'checked' : '' ?>> Add sample plans, FAQs, timeline &amp; legal page templates (recommended — edit later in admin)</label>
      <button class="btn btn-primary btn-block" type="submit">Install now</button>
    </form>
    <?php else: ?><div class="alert alert-bad">Fix the items marked ✖ above, then refresh this page.</div><?php endif; ?>
  <?php endif; ?>
</div></body></html>
